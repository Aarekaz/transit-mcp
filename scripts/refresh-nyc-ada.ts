/** Regenerates src/regions/nyc-ada.ts from MTA's "MTA Subway Stations" dataset on
 * data.ny.gov (station ADA status overall and by direction, keyed by GTFS Stop ID).
 * The supplemented subway GTFS publishes no wheelchair_boarding, so this reviewed file is
 * the station accessibility source. Review the diff before committing.
 *   bun scripts/refresh-nyc-ada.ts [path/to/stations.csv] */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE_URL = 'https://data.ny.gov/api/views/39hk-dx4f/rows.csv?accessType=DOWNLOAD';
const local = process.argv[2];
const text = local ? readFileSync(local, 'utf8') : await (await fetch(SOURCE_URL)).text();
const retrievedAt = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
const sha256 = createHash('sha256').update(text).digest('hex');

function parseCsv(input: string): string[][] {
  const rows: string[][] = []; let row: string[] = [], field = '', quoted = false;
  for (let i = 0; i < input.length; i++) {
    const ch = input[i]!;
    if (quoted) { if (ch === '"' && input[i + 1] === '"') { field += '"'; i++; } else if (ch === '"') quoted = false; else field += ch; continue; }
    if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') { if (ch === '\r' && input[i + 1] === '\n') i++; row.push(field); rows.push(row); row = []; field = ''; }
    else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.length > 1);
}

const [header, ...rows] = parseCsv(text);
const column = (name: string) => { const index = header!.indexOf(name); if (index < 0) throw new Error(`Missing column ${name}`); return index; };
const [id, ada, north, south, notes] = ['GTFS Stop ID', 'ADA', 'ADA Northbound', 'ADA Southbound', 'ADA Notes'].map(column) as [number, number, number, number, number];
const flag = (value: string, allowed: string[]) => { if (!allowed.includes(value)) throw new Error(`Unexpected ADA value ${value}`); return Number(value); };
const stations: Record<string, [number, number, number, string?]> = {};
for (const row of rows) {
  const stop = row[id]!.trim();
  if (!/^[A-Z0-9]{3}$/.test(stop)) throw new Error(`Unexpected GTFS Stop ID ${stop}`);
  if (stations[stop]) throw new Error(`Duplicate GTFS Stop ID ${stop}`);
  const overall = flag(row[ada]!, ['0', '1', '2']), n = flag(row[north]!, ['0', '1']), s = flag(row[south]!, ['0', '1']);
  // 2 is MTA's "partially accessible": usable in the listed direction(s) only.
  if (overall === 1 && (n !== 1 || s !== 1) || overall === 0 && (n || s) || overall === 2 && n === s) throw new Error(`Inconsistent ADA directions for ${stop}`);
  const note = row[notes]!.trim();
  stations[stop] = note && note !== 'NaN' ? [overall, n, s, note] : [overall, n, s];
}
if (Object.keys(stations).length < 400) throw new Error('Station list implausibly short');

const sorted = Object.fromEntries(Object.entries(stations).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(new URL('../src/regions/nyc-ada.ts', import.meta.url), `// Generated by scripts/refresh-nyc-ada.ts. Do not edit by hand.
/** MTA Subway Stations (data.ny.gov 39hk-dx4f): GTFS Stop ID to [ADA, northbound, southbound, note?].
 * ADA 1 = accessible, 2 = partially accessible (directions flagged 1 only), 0 = not accessible.
 * Northbound/southbound are the GTFS platform suffixes N and S. */
export const NYC_ADA_SOURCE = { url: ${JSON.stringify(SOURCE_URL)}, retrievedAt: ${JSON.stringify(retrievedAt)}, sha256: ${JSON.stringify(sha256)} } as const;
export const NYC_STATION_ADA: Readonly<Record<string, readonly [0 | 1 | 2, 0 | 1, 0 | 1, string?]>> = ${JSON.stringify(sorted)};
`);
